use std::env;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use crate::i18n::{LANGUAGE_NAME, parse};

// Constants
const UPDATE_VARIABLE: &str = "UPDATE_LANGUAGES";
const ISSUES: &str = "https://github.com/TripleT3005/TrayReveal/issues";
const TITLE_PREFIX: &str = "# TrayReveal language file: ";
const CATEGORY_PREFIX: &str = "# Category: ";
const REVIEWED_PREFIX: &str = "# Reviewed by: ";
const CATEGORIES: [(&str, &str); 3] = [
    ("standard", "Standard languages / Standardsprachen"),
    ("dialect", "Dialects / Dialekte"),
    ("fun", "Fun languages / Spaßsprachen"),
];

// Types
struct LanguageFile {
    code: String,
    english: String,
    category: String,
    name: String,
    reviewers: Vec<String>,
}

// Generation
fn read_languages(directory: &Path) -> Vec<LanguageFile> {
    let mut languages: Vec<LanguageFile> = fs::read_dir(directory)
        .unwrap()
        .flatten()
        .map(|file| file.path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "lang")
        })
        .map(|path| read_language(&path))
        .collect();
    languages.sort_by(|left, right| left.code.cmp(&right.code));
    languages
}

fn read_language(path: &Path) -> LanguageFile {
    let content = fs::read_to_string(path).unwrap();
    let header = |prefix: &str| {
        content
            .lines()
            .find_map(|line| line.strip_prefix(prefix))
            .unwrap_or_else(|| panic!("{} has no line starting with {prefix:?}", path.display()))
            .trim()
            .to_owned()
    };
    let code = path.file_stem().unwrap().to_string_lossy().into_owned();
    let title = header(TITLE_PREFIX);
    let english = title
        .strip_suffix(&format!("({code})"))
        .unwrap_or_else(|| panic!("{}: the title must end with ({code})", path.display()))
        .trim()
        .to_owned();
    let reviewers = header(REVIEWED_PREFIX)
        .split(',')
        .filter_map(|name| name.trim().strip_prefix('@'))
        .map(str::to_owned)
        .collect();
    LanguageFile {
        name: parse(&content).remove(LANGUAGE_NAME).unwrap_or_default(),
        category: header(CATEGORY_PREFIX),
        english,
        reviewers,
        code,
    }
}

fn document(languages: &[LanguageFile]) -> String {
    let mut text = format!(
        "# Languages

[English](#english) · [Deutsch](#deutsch)

## English

All translations were generated by Claude (AI). Files that a person has checked name the reviewer in the table and in the file itself. If you notice a mistake or know a better wording, please open an [issue]({ISSUES}) or a pull request; reviewers are credited with their GitHub name if they agree.

The codes follow [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO 639 language codes, ISO 3166 regions and ISO 15924 scripts. Dialects use their ISO 639-3 code where one exists, everything else a private-use code with `-x-`. Dialects and fun languages are only offered in the menu, never chosen automatically. Missing texts fall back to German for the German dialects and to English otherwise.

This list is generated from the headers of the files in [`lang`](lang). After changing them, run `$env:{UPDATE_VARIABLE} = 1; cargo test language_list` to update it; the CI fails if it is out of date.

## Deutsch

Alle Übersetzungen wurden von Claude (KI) erzeugt. Dateien, die eine Person geprüft hat, nennen die prüfende Person in der Tabelle und in der Datei selbst. Wenn dir ein Fehler auffällt oder du eine bessere Formulierung kennst, eröffne gern ein [Issue]({ISSUES}) oder einen Pull Request; mit Einverständnis wird die prüfende Person mit ihrem GitHub-Namen genannt.

Die Codes folgen [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO-639-Sprachcodes, ISO-3166-Regionen und ISO-15924-Schriften. Dialekte nutzen ihren ISO-639-3-Code, sofern es einen gibt, alles andere einen Private-Use-Code mit `-x-`. Dialekte und Spaßsprachen werden nur im Menü angeboten, nie automatisch gewählt. Fehlende Texte fallen bei den deutschen Dialekten auf Deutsch zurück, sonst auf Englisch.

Diese Liste wird aus den Köpfen der Dateien in [`lang`](lang) erzeugt. Nach Änderungen daran aktualisiert `$env:{UPDATE_VARIABLE} = 1; cargo test language_list` sie; die CI schlägt fehl, wenn sie veraltet ist.
"
    );
    for (category, title) in CATEGORIES {
        let _ = write!(
            text,
            "\n## {title}\n\n| Code | Language | Name in the menu | Reviewed by |\n|---|---|---|---|\n"
        );
        for language in languages
            .iter()
            .filter(|language| language.category == category)
        {
            let reviewers = if language.reviewers.is_empty() {
                "–".to_owned()
            } else {
                language
                    .reviewers
                    .iter()
                    .map(|name| format!("[@{name}](https://github.com/{name})"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let _ = writeln!(
                text,
                "| `{}` | {} | {} | {reviewers} |",
                language.code, language.english, language.name
            );
        }
    }
    text
}

// Tests
#[test]
fn language_list_is_up_to_date() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let languages = read_languages(&root.join("lang"));
    for language in &languages {
        assert!(
            CATEGORIES
                .iter()
                .any(|(category, _)| *category == language.category),
            "{} has the unknown category {}",
            language.code,
            language.category
        );
    }
    let expected = document(&languages);
    let path = root.join("LANGUAGES.md");
    if env::var_os(UPDATE_VARIABLE).is_some() {
        fs::write(&path, &expected).unwrap();
    }
    let actual = fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        actual == expected,
        "LANGUAGES.md is out of date, run `$env:{UPDATE_VARIABLE} = 1; cargo test language_list`"
    );
}
